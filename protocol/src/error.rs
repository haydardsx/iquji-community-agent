use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, Eq, PartialEq, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum AgentError {
    ConfigurationInvalid,
    ConfigurationNotPrivate,
    ConfigurationMetadataUnavailable,
    ConfigurationMetadataInvalid,
    ModelUnsupported,
    ExecutableUnavailable,
    ExecutableNotRegular,
    ExecutableNotExecutable,
    ExecutableDigestMismatch,
    ProcessFailed,
    ProcessIo,
    ProbeTimedOut,
    ProbeCancelled,
    ProbeOutputLimit,
    VersionUnsupported,
    CapabilitiesUnsupported,
    PlatformUnsupported,
    ProtocolInvalid,
    ProtocolUnsupported,
    RequestInvalid,
    SessionUnsupported,
    SessionMismatch,
    TurnTimedOut,
    TurnCancelled,
    TurnOutputLimit,
    AuthenticationRequired,
    ProviderCredentialMissing,
    AgentRequestFailed,
    AttachmentInvalid,
    AttachmentUnavailable,
    AttachmentChanged,
    AttachmentUnsupported,
}

impl AgentError {
    pub const fn code(self) -> &'static str {
        match self {
            Self::ConfigurationInvalid => "configuration_invalid",
            Self::ConfigurationNotPrivate => "configuration_not_private",
            Self::ConfigurationMetadataUnavailable => "configuration_metadata_unavailable",
            Self::ConfigurationMetadataInvalid => "configuration_metadata_invalid",
            Self::ModelUnsupported => "model_unsupported",
            Self::ExecutableUnavailable => "executable_unavailable",
            Self::ExecutableNotRegular => "executable_not_regular",
            Self::ExecutableNotExecutable => "executable_not_executable",
            Self::ExecutableDigestMismatch => "executable_digest_mismatch",
            Self::ProcessFailed => "process_failed",
            Self::ProcessIo => "process_io",
            Self::ProbeTimedOut => "probe_timed_out",
            Self::ProbeCancelled => "probe_cancelled",
            Self::ProbeOutputLimit => "probe_output_limit",
            Self::VersionUnsupported => "version_unsupported",
            Self::CapabilitiesUnsupported => "capabilities_unsupported",
            Self::PlatformUnsupported => "platform_unsupported",
            Self::ProtocolInvalid => "protocol_invalid",
            Self::ProtocolUnsupported => "protocol_unsupported",
            Self::RequestInvalid => "request_invalid",
            Self::SessionUnsupported => "session_unsupported",
            Self::SessionMismatch => "session_mismatch",
            Self::TurnTimedOut => "turn_timed_out",
            Self::TurnCancelled => "turn_cancelled",
            Self::TurnOutputLimit => "turn_output_limit",
            Self::AuthenticationRequired => "authentication_required",
            Self::ProviderCredentialMissing => "provider_credential_missing",
            Self::AgentRequestFailed => "agent_request_failed",
            Self::AttachmentInvalid => "attachment_invalid",
            Self::AttachmentUnavailable => "attachment_unavailable",
            Self::AttachmentChanged => "attachment_changed",
            Self::AttachmentUnsupported => "attachment_unsupported",
        }
    }
}
